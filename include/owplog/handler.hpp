#ifndef OWPLOG_HANDLER_HPP
#define OWPLOG_HANDLER_HPP

/**
 * @file handler.hpp
 * @brief Handler interfaces and built-in console/file handler implementations.
 */

#include <filesystem>

#include "owplog/filter.hpp"

#include <fstream>
#include <iostream>
#include <memory>
#include <mutex>
#include <string>
#include <unistd.h>
#include <vector>

namespace owplog {

/**
 * @brief Base class for output destinations.
 * @note Handler implementations must tolerate concurrent producer activity because
 *       dispatch is asynchronous and may involve multiple handler instances.
 */
class LogHandler {
    public:
        /** Virtual destructor for polymorphic handler deletion. */
        virtual ~LogHandler() = default;

        /**
         * @brief Add a handler-local filter.
         * @param filter Filter to append.
         * @pre `filter` should be non-null for useful filtering.
         * @post Filter is appended to handler-local filter list.
         * @throws May propagate allocation failures when growing filter storage.
         */
        void add_filter(LogFilterPtr filter);
        /**
         * @brief Remove all handler-local filters.
         * @pre None.
         * @post Handler-local filter list is empty.
         * @throws No intentional exceptions.
         */
        void clear_filters();
        /**
         * @brief Evaluate handler-local filters.
         * @param record Record under evaluation.
         * @return True when all filters allow this record.
         * @pre `record` is valid for read-only inspection.
         * @post Handler state is unchanged.
         * @throws No intentional exceptions.
         */
        bool should_log(const LogRecord& record) const;

        void set_maximum_buffer_size(uint32_t size);

        /**
         * @brief Write one preformatted record.
         * @param record Original record metadata.
         * @param formatted Final preformatted text.
         * @pre `formatted` is typically generated by the active formatter.
         * @post Handler has attempted to persist/emit the record.
         * @throws Implementation-defined I/O exceptions if enabled.
         */
        virtual void write(const LogRecord& record, const std::string& formatted) = 0;
        /**
         * @brief Flush handler output buffers.
         * @pre None.
         * @post Buffered handler data is requested to be flushed to underlying medium.
         * @throws Implementation-defined I/O exceptions if enabled.
         */
        virtual void flush();

    protected:
        /** The maximum number of bytes that may be written prior to flushing */
        uint32_t maximum_buffer_size_ = 1024 * 1024;
        /** A buffer to write to prior to flushing */
        std::string buffer_;

    private:
        /** Mutex protecting handler-local filter list. */
        mutable std::mutex filter_mutex_;
        /** Handler-local filters applied before write. */
        std::vector<LogFilterPtr> filters_;
};

/**
 * @brief Handler that writes to stdout/stderr.
 */
class ConsoleHandler final : public LogHandler {
public:
    /**
     * @brief Construct console handler behavior.
     * @param stderr_for_errors Route error and above to stderr.
     * @param suppress_captured_streams Avoid echo-looping captured stdio.
     * @pre None.
     * @post Console handler configuration is fixed for instance lifetime.
     * @throws No intentional exceptions.
     */
    ConsoleHandler(bool stderr_for_errors = true, bool suppress_captured_streams = true);
    /** @copydoc LogHandler::write */
    void write(const LogRecord& record, const std::string& formatted) override;
    /** @copydoc LogHandler::flush */
    void flush() override;
    void set_stderr_descriptor(int descriptor);
    void set_stdout_descriptor(int descriptor);

private:
    /** Whether error-level records should go to stderr. */
    bool stderr_for_errors_;
    /** Whether captured stdout/stderr records should be suppressed on console output. */
    bool suppress_captured_streams_;
    /** Mutex protecting console stream writes and flushes. */
    std::mutex io_mutex_;
    int stdout_descriptor_ = STDOUT_FILENO;
    int stderr_descriptor_ = STDERR_FILENO;
};

/**
 * @brief Handler that writes to a file stream.
 */
class FileHandler final : public LogHandler {
public:
        /**
         * @brief Construct file handler.
         * @param path Destination file path.
         * @param append True to append, false to truncate.
         * @pre `path` must be writable by current process.
         * @post On success, file stream is open.
         * @throws `std::runtime_error` when file open fails.
         */
        explicit FileHandler(const std::string& path, bool append = true);
        explicit FileHandler(const std::filesystem::path& path, bool append = true);
        explicit FileHandler(const char* path, bool append = true);
    /** @copydoc LogHandler::write */
    void write(const LogRecord& record, const std::string& formatted) override;
    /** @copydoc LogHandler::flush */
    void flush() override;

private:
    /** Mutex protecting file stream writes and flushes. */
    std::mutex file_mutex_;
    /** Output stream backing this handler. */
    std::ofstream stream_;
};

/** Shared-pointer alias for handler objects. */
using LogHandlerPtr = std::shared_ptr<LogHandler>;

} // namespace owplog

#endif
