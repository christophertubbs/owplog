#ifndef OWPLOG_SINK_HPP
#define OWPLOG_SINK_HPP

/**
 * @file sink.hpp
 * @brief Sink interfaces and built-in console/file sink implementations.
 */

#include "owplog/filter.hpp"

#include <fstream>
#include <memory>
#include <mutex>
#include <string>
#include <vector>

namespace owplog {

/**
 * @brief Base class for output destinations.
 * @note Sink implementations must tolerate concurrent producer activity because
 *       dispatch is asynchronous and may involve multiple sink instances.
 */
class LogSink {
public:
    /** Virtual destructor for polymorphic sink deletion. */
    virtual ~LogSink() = default;

    /**
     * @brief Add a sink-local filter.
     * @param filter Filter to append.
     * @pre `filter` should be non-null for useful filtering.
     * @post Filter is appended to sink-local filter list.
     * @throws May propagate allocation failures when growing filter storage.
     */
    void add_filter(LogFilterPtr filter);
    /**
     * @brief Remove all sink-local filters.
     * @pre None.
     * @post Sink-local filter list is empty.
     * @throws No intentional exceptions.
     */
    void clear_filters();
    /**
     * @brief Evaluate sink-local filters.
     * @param record Record under evaluation.
     * @return True when all filters allow this record.
     * @pre `record` is valid for read-only inspection.
     * @post Sink state is unchanged.
     * @throws No intentional exceptions.
     */
    bool should_log(const LogRecord& record) const;

    /**
     * @brief Write one preformatted record.
     * @param record Original record metadata.
     * @param formatted Final preformatted text.
     * @pre `formatted` is typically generated by the active formatter.
     * @post Sink has attempted to persist/emit the record.
     * @throws Implementation-defined I/O exceptions if enabled.
     */
    virtual void write(const LogRecord& record, const std::string& formatted) = 0;
    /**
     * @brief Flush sink output buffers.
     * @pre None.
     * @post Buffered sink data is requested to be flushed to underlying medium.
     * @throws Implementation-defined I/O exceptions if enabled.
     */
    virtual void flush();

private:
    /** Mutex protecting sink-local filter list. */
    mutable std::mutex filter_mutex_;
    /** Sink-local filters applied before write. */
    std::vector<LogFilterPtr> filters_;
};

/**
 * @brief Sink that writes to stdout/stderr.
 */
class ConsoleSink final : public LogSink {
public:
    /**
     * @brief Construct console sink behavior.
     * @param stderr_for_errors Route error and above to stderr.
     * @param suppress_captured_streams Avoid echo-looping captured stdio.
     * @pre None.
     * @post Console sink configuration is fixed for instance lifetime.
     * @throws No intentional exceptions.
     */
    ConsoleSink(bool stderr_for_errors = true, bool suppress_captured_streams = true);
    /** @copydoc LogSink::write */
    void write(const LogRecord& record, const std::string& formatted) override;
    /** @copydoc LogSink::flush */
    void flush() override;

private:
    /** Whether error-level records should go to stderr. */
    bool stderr_for_errors_;
    /** Whether captured stdout/stderr records should be suppressed on console output. */
    bool suppress_captured_streams_;
    /** Mutex protecting console stream writes and flushes. */
    std::mutex io_mutex_;
};

/**
 * @brief Sink that writes to a file stream.
 */
class FileSink final : public LogSink {
public:
    /**
     * @brief Construct file sink.
     * @param path Destination file path.
     * @param append True to append, false to truncate.
     * @pre `path` must be writable by current process.
     * @post On success, file stream is open.
     * @throws `std::runtime_error` when file open fails.
     */
    explicit FileSink(const std::string& path, bool append = true);
    /** @copydoc LogSink::write */
    void write(const LogRecord& record, const std::string& formatted) override;
    /** @copydoc LogSink::flush */
    void flush() override;

private:
    /** Mutex protecting file stream writes and flushes. */
    std::mutex file_mutex_;
    /** Output stream backing this sink. */
    std::ofstream stream_;
};

/** Shared-pointer alias for sink objects. */
using LogSinkPtr = std::shared_ptr<LogSink>;

} // namespace owplog

#endif
