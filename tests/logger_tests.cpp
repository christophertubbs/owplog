#include "owplog/c_api.h"
#include "owplog/logger.hpp"

#include <gtest/gtest.h>

#include <atomic>
#include <chrono>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <string>
#include <thread>
#include <vector>

namespace {

/**
 * @brief Test sink that only counts writes.
 */
class CountingSink final : public owplog::LogHandler {
public:
    /** @brief Increment count for each delivered record. */
    void write(const owplog::LogRecord&, const std::string&) override {
        ++count_;
    }

    /** @brief Read current write count. */
    int count() const {
        return count_.load();
    }

private:
    /** Atomic counter tracking observed writes. */
    std::atomic<int> count_{0};
};

/**
 * @brief Construct unique temp file path for test output.
 * @param name Prefix component for file name.
 * @return Unique temporary log file path.
 */
std::filesystem::path temp_log_path(const std::string& name) {
    // Time-derived suffix to avoid path collisions across tests.
    const auto now = std::chrono::high_resolution_clock::now().time_since_epoch().count();
    return std::filesystem::temp_directory_path() / (name + "_" + std::to_string(now) + ".log");
}

} // namespace

TEST(LoggerTest, HandlesConcurrentLogging) {
    // Shared singleton logger under test.
    auto& logger = owplog::Logger::instance();
    logger.shutdown();
    logger.clear_sinks();
    logger.clear_filters();
    logger.set_level(owplog::LogLevel::Trace);

    auto sink = std::make_shared<CountingSink>();
    logger.add_sink(sink);

    // Number of producer threads used for concurrency coverage.
    constexpr int thread_count = 8;
    // Records generated by each thread.
    constexpr int per_thread = 200;

    std::vector<std::thread> threads;
    threads.reserve(thread_count);
    for (int t = 0; t < thread_count; ++t) {
        threads.emplace_back([t]() {
            for (int i = 0; i < per_thread; ++i) {
                owplog::Logger::instance().log(
                    owplog::LogLevel::Info,
                    "message-" + std::to_string(i),
                    "thread-" + std::to_string(t));
            }
        });
    }

    for (auto& th : threads) {
        th.join();
    }

    logger.flush();
    EXPECT_EQ(sink->count(), thread_count * per_thread);
}

TEST(LoggerTest, AppliesLevelFilter) {
    auto& logger = owplog::Logger::instance();
    logger.shutdown();
    logger.clear_sinks();
    logger.clear_filters();
    logger.set_level(owplog::LogLevel::Trace);

    auto sink = std::make_shared<CountingSink>();
    logger.add_sink(sink);
    logger.add_filter(std::make_shared<owplog::LevelFilter>(owplog::LogLevel::Warning));

    logger.log(owplog::LogLevel::Info, "not-kept", "test");
    logger.log(owplog::LogLevel::Warning, "kept", "test");
    logger.log(owplog::LogLevel::Error, "kept-too", "test");
    logger.flush();

    EXPECT_EQ(sink->count(), 2);
}

TEST(LoggerTest, CApiWritesToFile) {
    auto& logger = owplog::Logger::instance();
    logger.shutdown();
    logger.clear_sinks();
    logger.clear_filters();
    logger.set_level(owplog::LogLevel::Trace);
    logger.set_formatter(std::make_shared<owplog::PatternFormatter>("%f:%l %F rank=%r lang=%g %m"));

    // Output path used by upstream logger sink.
    const auto path = temp_log_path("owplog_c_api");
    ASSERT_TRUE(logger.add_file_sink(path.string(), false));

    const owplog_sublogger_handle handle = owplog_logger_add_sublogger("c.test.sub");
    ASSERT_GT(handle, 0);

    owplog_logger_log(OWPLOG_LOG_INFO, "c.test", "hello from c abi");
    owplog_logger_log_sublogger(OWPLOG_LOG_INFO, handle, "hello from sublogger handle");
    const owplog_log_meta meta{"unit_test.c", 321, "test_fn", "python", 7};
    owplog_logger_log_ex(OWPLOG_LOG_INFO, "c.test.meta", "hello from ex", &meta);
    logger.flush();

    std::ifstream in(path);
    ASSERT_TRUE(in.is_open());
    // Entire file content used for substring assertion.
    std::string content((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    EXPECT_NE(content.find("hello from c abi"), std::string::npos);
    EXPECT_NE(content.find("hello from sublogger handle"), std::string::npos);
    EXPECT_NE(content.find("unit_test.c:321"), std::string::npos);
    EXPECT_NE(content.find("test_fn"), std::string::npos);
    EXPECT_NE(content.find("rank=7"), std::string::npos);
    EXPECT_NE(content.find("lang=python"), std::string::npos);

    std::filesystem::remove(path);
}

TEST(LoggerTest, CapturesStdout) {
    auto& logger = owplog::Logger::instance();
    logger.shutdown();
    logger.clear_sinks();
    logger.clear_filters();
    logger.set_level(owplog::LogLevel::Trace);

    // Output path used for stdout capture assertions.
    const auto path = temp_log_path("owplog_capture");
    ASSERT_TRUE(logger.add_file_sink(path.string(), false));

    ASSERT_TRUE(logger.start_stdio_capture(true, false));
    std::printf("captured-line-from-stdout\n");
    std::fflush(stdout);
    std::this_thread::sleep_for(std::chrono::milliseconds(50));
    logger.stop_stdio_capture();
    logger.flush();

    std::ifstream in(path);
    ASSERT_TRUE(in.is_open());
    std::string content((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    EXPECT_NE(content.find("captured-line-from-stdout"), std::string::npos);

    std::filesystem::remove(path);
}

TEST(LoggerTest, FormatterSupportsRankToken) {
    // Synthetic record used to validate rank token expansion.
    owplog::LogRecord record;
    record.timestamp = std::chrono::system_clock::now();
    record.level = owplog::LogLevel::Info;
    record.logger_name = "rank.test";
    record.message = "hello";
    record.thread_id = std::this_thread::get_id();
    record.rank = 42;

    owplog::PatternFormatter formatter("%N rank=%r %m");
    const std::string formatted = formatter.format(record);
    EXPECT_NE(formatted.find("rank=42"), std::string::npos);
}
